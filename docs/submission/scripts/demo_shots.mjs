// 参赛截图：手机 390×844@2x（01~08）与桌面 1280×800（d_shop / d_battle）
import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const URL = process.env.URL || 'http://localhost:3100';
const OUT = process.argv[2];
const END = JSON.parse(readFileSync(process.argv[3], 'utf8'));
const desk = process.env.VP === 'desk';
const SEED = process.env.SEED || 'demo159';
const browser = await chromium.launch();
const ctx = await browser.newContext(desk ? { viewport: { width: 1280, height: 800 } } : { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await ctx.addInitScript(() => { try { localStorage.setItem('jw.name', JSON.stringify('参赛者')); localStorage.setItem('jw.tutorialDone', 'true'); } catch {} });
const page = await ctx.newPage();
const sleep = (ms) => page.waitForTimeout(ms);
const S = () => page.evaluate(() => window.__jw.state);
const D = (a) => page.evaluate((x) => { const r = window.__jw.dispatch(x); return r?.error; }, a);
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });
await page.goto(URL + '/?debug');
await page.waitForSelector('.scene--home', { timeout: 30000 });
await sleep(1500);
if (!desk) await shot('01_home');
await page.evaluate((s) => window.__jw.start(s, 'normal'), SEED);
await page.waitForSelector('.scene--arena');
await sleep(1200);
await page.click('.ar-card >> nth=1'); await sleep(500);
if (!desk) await shot('02_arena');
await page.click('.ar-go');
await page.waitForSelector('.scene--game');
if (desk) {
  await page.evaluate((st) => { window.__jw.setRun(st); window.__jw.go('game'); }, END);
  await sleep(1500);
  await shot('d_shop');
  await page.click('.act-fight');
  await page.waitForSelector('.scene--battle');
  try { await page.waitForSelector('.big-skill', { timeout: 12000 }); await sleep(200); } catch { await sleep(2500); }
  await shot('d_battle');
  await browser.close();
  process.exit(0);
}
await sleep(500);
const unitIdx = (s) => s.shop.map((x, i) => [x, i]).filter(([x]) => x.kind === 'unit' && x.price <= s.gold).map(([, i]) => i);
let s = await S();
await D({ type: 'buy', slot: unitIdx(s)[0], to: 0 });
s = await S(); await D({ type: 'buy', slot: unitIdx(s)[0], to: 1 });
s = await S(); await D({ type: 'equip', slot: s.shop.findIndex((x) => x.kind === 'equip' && x.price <= s.gold), unitIndex: 0 });
await sleep(800);
await page.click('.act-fight');
await page.waitForSelector('.scene--battle');
await page.waitForSelector('.big-skill', { timeout: 20000 });
await sleep(180);
await shot('05_battle_skill');
await page.waitForSelector('.result-go', { timeout: 60000 });
await sleep(1600);
await shot('06_result');
await page.click('.result-go');
await page.waitForSelector('.np-opt');
await sleep(900);
await shot('04_headline');
await page.click('.np-opt >> nth=0');
await page.waitForSelector('.scene--game');
await sleep(800);
await page.click('.hud-codex'); await sleep(900);
await shot('07_codex');
await page.click('.modal-x'); await sleep(400);
// 终局商店：满编、带装备，展开羁绊面板
await page.evaluate((st) => { window.__jw.setRun(st); window.__jw.go('game'); }, END);
await page.waitForSelector('.scene--game');
await sleep(1500);
await shot('03_shop');
await page.click('.sp-toggle'); await sleep(600);
await shot('03b_shop_synergy');
await page.click('.sp-toggle'); await sleep(400);
await page.click('.act-fight');
await page.waitForSelector('.scene--battle');
await sleep(500);
await page.evaluate(() => window.__jw.skip());
await page.waitForSelector('.result-go', { timeout: 60000 });
await sleep(800);
await page.click('.result-go');
await page.waitForSelector('.scene--over');
await sleep(3000);
await shot('08_over');
await browser.close();
